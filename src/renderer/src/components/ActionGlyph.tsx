import type { JSX } from 'react';

export function PixelIcon({
  rows,
  palette,
}: {
  rows: string[];
  palette: Record<string, string>;
}): JSX.Element {
  return (
    <svg width="18" height="18" viewBox="0 0 16 16" shapeRendering="crispEdges" style={{ imageRendering: 'pixelated' }}>
      {rows.flatMap((row, y) =>
        row.split('').map((c, x) =>
          c === '.' || palette[c] === 'transparent' ? null : (
            <rect key={`${x}-${y}`} x={x} y={y} width={1} height={1} fill={palette[c]} />
          ),
        ),
      )}
    </svg>
  );
}

